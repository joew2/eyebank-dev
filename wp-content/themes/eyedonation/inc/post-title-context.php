<?php
/** Core post titles rendered outside the main loop must use their selected post. */
defined('ABSPATH') || exit;
add_filter('render_block_core/post-title', static function ($html, $parsed, $block) {
    $id = (int) ($block->context['postId'] ?? 0);
    if (!$id || get_post_type($id) !== 'post' || $id === (int) ($GLOBALS['post']->ID ?? 0)) return $html;
    $title = wp_kses_post(get_the_title($id));
    // REST requests have no current page; core returns before creating a wrapper.
    if (trim($html) === '' && $title !== '') {
        $attrs = $parsed['attrs'] ?? [];
        $level = (int) ($attrs['level'] ?? 2);
        $tag = $level === 0 ? 'p' : 'h'.max(1, min(6, $level));
        $classes = 'wp-block-post-title';
        if (!empty($attrs['className'])) $classes .= ' '.$attrs['className'];
        if (!empty($attrs['isLink'])) {
            $title = '<a href="'.esc_url(get_permalink($id)).'">'.$title.'</a>';
        }
        return '<'.$tag.' class="'.esc_attr($classes).'">'.$title.'</'.$tag.'>';
    }
    // Retain the native block wrapper and link attributes generated by WordPress.
    if (!empty($parsed['attrs']['isLink'])) {
        return preg_replace_callback('~(<a\b[^>]*>).*?(</a>)~s', static fn($m)=>$m[1].$title.$m[2], $html, 1);
    }
    return preg_replace_callback('~^(\s*<(h[1-6]|p)\b[^>]*>).*?(</\2>\s*)$~s', static fn($m)=>$m[1].$title.$m[3], $html, 1);
}, 10, 3);
